    <section id="edit">
      <h2><span>5</span>修改、撤销与手动编辑</h2>
      <h3>只改这一页</h3>
      <p>在中间翻到要改的页，点「只改这一页」，输入框上方会出现“只改第 N 页”的标记。这时你说的话只针对这一页，其他页不会动。点标记上的 × 取消。</p>
      <h3>撤销</h3>
      <p>每次修改前系统都会保存一个版本（最多保留 30 个）。点顶部「撤销」回到上一版，可以连续撤销。</p>
      <h3>手动编辑</h3>
      <p>点「手动编辑」或「逐页编辑」进入编辑器：左侧是页面列表，可以新增、复制、删除页面，用 ↑ ↓ 调整顺序；右侧编辑标题、要点、版式（封面、学习目标、要点、左右对比、结构图、课堂提问、章节过渡、小结）、所属环节和讲稿。改完点「保存」。</p>
      <div class="tip warn"><b>注意</b>手动编辑和 AI 修改是同一份课件。如果你在编辑器里改了还没保存，又回到工作室让 AI 修改，未保存的内容会丢失。</div>
    </section>

