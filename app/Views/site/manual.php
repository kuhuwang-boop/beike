    <section id="diagrams">
      <h2><span>9</span>结构图</h2>
      <p>有先后、有层级、有对比的内容，画成图比列成文字更好懂。说“把适合的页面改成结构图”，结构图设计师会挑出合适的页面，按内容选版式，把文字页改成结构图。</p>
      <table class="tbl">
        <tr><th>内容是什么样的</th><th>用哪种结构图</th></tr>
        <tr><td>有先后的步骤、环节</td><td>流程</td></tr>
        <tr><td>几步做完又回到起点（如 PDCA）</td><td>闭环</td></tr>
        <tr><td>按时间排的里程碑、发展历程</td><td>时间轴</td></tr>
        <tr><td>两种做法、两个概念、改前改后</td><td>左右对照</td></tr>
        <tr><td>三五个并列要点，没有先后</td><td>并列卡片</td></tr>
        <tr><td>几根支柱共同撑起一个结论</td><td>支柱</td></tr>
        <tr><td>三四个关键数据</td><td>大数字</td></tr>
        <tr><td>上少下多的层级（如布鲁姆分类）</td><td>金字塔</td></tr>
        <tr><td>逐级筛选、收窄</td><td>漏斗</td></tr>
        <tr><td>一个总概念拆成几类，类下有条目</td><td>分类树</td></tr>
        <tr><td>一个核心关联多个方面</td><td>中心辐射</td></tr>
        <tr><td>自上而下的层次，每层有若干模块</td><td>分层结构</td></tr>
        <tr><td>类型 → 内容 → 用途，每行一组</td><td>三栏对照</td></tr>
      </table>
      <h3>自己修改</h3>
      <p>在逐页编辑里把版式选成“结构图”：可以换结构图版式和风格（圆角卡片、直角线框、扁平极简），写一句导语，增删、上下移动条目，选一条“重点突出”。原来是要点页的，切换成结构图时会自动把要点搬成条目。</p>
      <h3>导出后还能改</h3>
      <p>下载的 PPT 里，结构图是 PowerPoint 原生的形状和文字框，不是图片。每个方块、箭头和文字都能直接改字、改颜色、挪位置。</p>
      <div class="tip"><b>体检里的结构图规则</b>相邻两页不要用同一种结构图；整套有 4 张以上时至少用 3 种版式，“并列卡片”和“流程”合计不超过一半；每个条目都要有标题和内容，不能只放两个字的空卡片；整套用同一种风格。</div>
    </section>

    <section id="template">
      <h2><span>10</span>套用学校 PPT 模板</h2>
      <p>很多学校、学院要求课件使用统一模板。把学校的模板文件（.pptx）上传一次，之后任何一份课件都能一键套用。所有相关设置都在左侧菜单的「学校模板与校徽」里（手机在「我的」里）。</p>
      <ol>
        <li>打开「学校模板与校徽」点「上传学校模板」；或者在课件工作室右上角点「样式」（手机在“更多”里），在样式窗口里点「上传学校模板」。</li>
        <li>系统会读取模板里的封面和内容页背景、校徽和色条等装饰、标题与正文的位置、主题色和字体，并给出封面页、内容页和结构图页的效果预览。</li>
        <li>确认没问题后填好名称，点「保存并使用」。以后在配色下拉框的「学校模板」分组里就能直接选。</li>
      </ol>
