    <section id="mine">
      <h2><span>7</span>因人而异：资料库、风格与技能</h2>
      <p>每位老师的学生不同、讲法不同、要求也不同。工作台会记住你的这些习惯，做出来的课件才像你自己做的。以下设置都只属于你自己的账号。</p>
      <h3>我的资料库</h3>
      <ul>
        <li>左侧菜单「我的资料库」：把平时的讲义、旧课件、教案一次上传（可多选、可拖入），按课程分类。在课件里上传的资料也会自动存进来，内容相同的不会重复保存。</li>
        <li>新建课件时输入课题，下方会列出资料库里<b>可能相关</b>的资料，默认勾选，开始制作时一起带进这节课。</li>
        <li>课件里点输入框上方的「资料库」可以随时再加；资料库页面的「做课件」按钮能直接用某份资料新建一节课。</li>
        <li>如果一节课没有添加任何资料，AI 团队会按课题自动参考资料库里最相关的几份，并在对话里告诉你参考了哪些。</li>
      </ul>
      <h3>我的备课风格</h3>
      <p>左侧菜单「我的备课风格」：填写你的学生情况、常用案例、语言风格（严谨规范 / 亲切口语 / 生动幽默）、每页信息量、每节课必须有的环节（案例导入、课堂互动、课程思政、随堂练习、实训任务、小结与作业）、不要这样做的事和其他习惯。保存后，所有 AI 成员生成和修改课件都按这份风格来。</p>
      <div class="tip"><b>不想自己填？</b>点「从我的资料库学习风格」，AI 会读你资料库里最近的旧课件和教案，总结出你的习惯并说明依据。它只会补充你还没填的项，确认后再保存。</div>
      <h3>我的技能</h3>
      <p>技能是一条可以反复使用的具体要求，比如“每个新概念先抛问题让学生猜，再揭晓答案”。在「我的备课风格」页面新建；不想自己写，就用一句话描述想要的效果，点「AI 帮我写」。可以勾选“以后新课件都自动带上”，也可以在每份课件里点「方法与技能」单独增减。你自己的技能会被 AI 团队优先遵守。</p>
      <h3>课型</h3>
      <p>新建课件时选课型：新授课、复习课、习题课、实验 / 实训课、研讨课、公开课 / 教学比赛。不同课型的课件结构不同，例如习题课按“题型 → 样例思路 → 变式练习 → 方法小结”组织，实训课把动手时间放在一半以上。课件页标题下方也能随时改课型。</p>
      <h3>常用指令</h3>
      <p>你经常对 AI 团队说的话，比如“每页不超过 4 条，案例换成护理专业的”，在课件页输入框上方点「存为常用」，以后一点就发。最多 12 条。</p>
    </section>

