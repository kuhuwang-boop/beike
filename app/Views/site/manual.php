      <h2><span>16</span>进阶：课程与教案</h2>
      <p>需要做专业认证、课程评估时，用左侧菜单的「课程与教案」。它按照<b>逆向设计（OBE）</b>组织：</p>
      <pre class="chain">毕业要求指标点 → 课程目标（含布鲁姆层级、权重） → 每次课的 BOPPPS 环节 → 课堂检测 / 题库 → 逐题成绩 → 达成度 → 改进下一轮</pre>
      <p>每一环都有程序化检查，结果可以复核：环节时长合计是否等于课时；每个目标有没有课堂评价和题目；题目的认知层级是否低于目标层级；学生主动学习时间是否少于 30%，有没有超过 20 分钟的连续讲授；目标权重合计是否为 100%；毕业要求有没有被支撑。</p>
      <h3>推荐流程（第一次约 30 分钟，之后每次课约 10 分钟）</h3>
      <ol>
        <li><b>新建课程</b>，把教学大纲原文整段粘贴进去。AI 的输出都会引用大纲原文并逐字核对：<span class="pill ok">已核验</span>表示引文确实出自大纲，<span class="pill bad">未找到</span>表示需要你重点看。</li>
        <li><b>目标与支撑矩阵</b>：点“AI 从大纲提取目标”，修改后保存；填写毕业要求指标点，在矩阵里标 H / M / L。</li>
        <li><b>课次与进度</b>：填写开课日期和每周上课的星期，一键生成全学期课次，可以跳过节假日。</li>
