<h2>最简单的用法（3 步）</h2>
<ol>
<li>打开「课件工作室」，写下课题，把平时的 Word / PPT / PDF 资料拖进去，点「开始制作」。</li>
<li>AI 课件团队自动分工完成：<b>教学设计师</b>梳理教学思路 → <b>课件设计师</b>做 PPT → <b>出题老师</b>加课堂互动 → <b>学科审核</b>对照你的资料核查内容。</li>
<li>预览满意后点右上角「下载 PPT」；不满意就直接在左边说，比如“第5页举个生活中的例子”。点任意一页再点“只改这一页”，修改就只针对那一页；改坏了点「撤销」。</li>
</ol>
<p class="muted">右侧「体检与改进」会按固定规则检查页数、文字量和互动环节，并列出 AI 相比你的原资料做了哪些调整。资料可以随时查看、修改或删除；课件、对话也都可以重命名、清空或删除。</p>
<hr>
<h2>进阶：课程与教案</h2>
<h3>这部分和一般备课工具的区别</h3>
<p>一般的工具是“先写内容，再想怎么考”。这里反过来，按照资深教师和专业认证要求的<b>逆向设计（OBE）</b>来组织：</p>
<pre class="chain">毕业要求指标点 → 课程目标（含布鲁姆层级、权重） → 每次课的 BOPPPS 环节 → 课堂检测 / 题库 → 逐题成绩 → 达成度 → 改进下一轮</pre>
<p>每一环都有<b>程序化检查</b>，不依赖 AI 的判断，结果可以复核：</p>
<ul>
<li>环节时长合计是否等于课时；</li>
<li>每个目标有没有课堂评价、有没有题目；题目的认知层级是否低于目标层级；</li>
<li>学生主动学习时间是否少于 30%，有没有超过 20 分钟的连续讲授；</li>
<li>目标权重合计是否为 100%；毕业要求有没有被支撑。</li>
</ul>

<h2>推荐流程（第一次约 30 分钟，之后每次课约 10 分钟）</h2>
<ol>
<li><b>新建课程</b>，把教学大纲原文整段粘贴进去。AI 所有输出都会引用大纲原文，系统逐字核对：标<span class="pill ok">已核验</span>表示引文确实出自大纲，标<span class="pill bad">未找到</span>表示 AI 可能在编造，需要你重点看。</li>
<li><b>目标与支撑矩阵</b>：点“AI 从大纲提取目标”，修改后保存；填写毕业要求指标点，在矩阵里标 H/M/L。</li>
<li><b>课次与进度</b>：填开课日期和每周上课的星期，一键生成全学期课次（可以跳过节假日）。</li>
<li><b>逐次备课</b>：勾选本次课的目标 → “AI 生成教案草稿” → 修改 → 保存。看右侧检查结果，把错误修完；可以再点“AI 督导评课”。</li>
<li><b>PPT 课件</b>：教案保存后点“PPT 课件”，用 AI 或直接按教案结构生成课件大纲，逐页修改后导出 .pptx（可在 PowerPoint 或 WPS 中继续编辑，讲稿在备注里）。</li>
<li><b>题库</b>：按“目标 × 层级”出题，页面上方的双向细目表能看出哪些格子是空的。</li>
<li><b>组卷</b>：按目标权重自动组卷，或手工勾选；导出 Word 试卷和答案。</li>
<li><b>考后</b>：下载成绩模板，用 Excel 填写逐题得分后导入 → 自动算出难度 P、区分度 D、信度 α 和各课程目标达成度 → “AI 生成持续改进建议”。</li>
<li><b>下学期</b>：在课程页点“复制到新学期”，课程目标、支撑矩阵、教案、PPT 课件、题库和上一轮反思都会一起带过去。</li>
</ol>

<h2>指标含义</h2>
<table class="tbl">
<tr><th>指标</th><th>算法</th><th>参考标准</th></tr>
<tr><td>难度 P</td><td>平均得分 ÷ 满分</td><td>0.3–0.9 较合适；&lt;0.3 偏难，&gt;0.9 偏易</td></tr>
<tr><td>区分度 D</td><td>(高分组27%均分 − 低分组27%均分) ÷ 满分</td><td>≥0.4 优，0.2–0.4 可用，&lt;0.2 差；负值通常说明答案或题意有问题</td></tr>
<tr><td>信度 α</td><td>Cronbach α = k/(k−1)·(1 − Σ题目方差 / 总分方差)</td><td>≥0.7 较好（课程考试 ≥0.6 可接受）</td></tr>
<tr><td>目标达成度</td><td>Σ该目标各题平均分 ÷ Σ该目标各题满分</td><td>默认阈值 0.70，可在课程设置中修改</td></tr>
</table>
